#!/usr/bin/env python3
"""Regenerate the README skills index and .claude-plugin/marketplace.json from skills/.

Usage:
    python3 scripts/sync_index.py           # rewrite both files
    python3 scripts/sync_index.py --check   # exit 1 if either is out of date
"""
import json
import re
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("PyYAML is required: python3 -m venv .venv && .venv/bin/pip install -r requirements.txt")

ROOT = Path(__file__).resolve().parent.parent
SKILLS_DIR = ROOT / "skills"
README = ROOT / "README.md"
MARKETPLACE = ROOT / ".claude-plugin" / "marketplace.json"

INDEX_START = "<!-- SKILLS-INDEX:START (generated by scripts/sync_index.py; do not edit by hand) -->"
INDEX_END = "<!-- SKILLS-INDEX:END -->"
INDEX_RE = re.compile(re.escape(INDEX_START) + r".*?" + re.escape(INDEX_END), re.S)


def read_frontmatter(path):
    """Return the YAML frontmatter of a Markdown file as a dict, or None if absent/invalid."""
    text = path.read_text(encoding="utf-8")
    match = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not match:
        return None
    try:
        data = yaml.safe_load(match.group(1))
    except yaml.YAMLError:
        return None
    return data if isinstance(data, dict) else None


def ready_skills():
    """Sorted (name, description) for every skill folder in skills/."""
    result = []
    for skill_dir in sorted(p for p in SKILLS_DIR.iterdir() if p.is_dir()):
        fm = read_frontmatter(skill_dir / "SKILL.md") if (skill_dir / "SKILL.md").exists() else None
        description = str((fm or {}).get("description", "")).strip()
        result.append((skill_dir.name, " ".join(description.split())))
    return result


def render_index(skills):
    lines = [INDEX_START, "| Skill | Description |", "|---|---|"]
    for name, description in skills:
        escaped = description.replace("|", "\\|")
        lines.append(f"| [{name}](skills/{name}/SKILL.md) | {escaped} |")
    if not skills:
        lines.append("| _none yet_ | |")
    lines.append(INDEX_END)
    return "\n".join(lines)


def expected_readme(skills):
    text = README.read_text(encoding="utf-8")
    if not INDEX_RE.search(text):
        raise SystemExit(f"README.md is missing the index markers:\n{INDEX_START}\n{INDEX_END}")
    return INDEX_RE.sub(lambda _: render_index(skills), text)


def expected_marketplace(skills):
    data = json.loads(MARKETPLACE.read_text(encoding="utf-8"))
    data["plugins"][0]["skills"] = [f"./skills/{name}" for name, _ in skills]
    return json.dumps(data, indent=2) + "\n"


def out_of_date():
    """List of files whose content differs from what skills/ implies."""
    skills = ready_skills()
    stale = []
    if README.read_text(encoding="utf-8") != expected_readme(skills):
        stale.append("README.md")
    if MARKETPLACE.read_text(encoding="utf-8") != expected_marketplace(skills):
        stale.append(".claude-plugin/marketplace.json")
    return stale


def main():
    if "--check" in sys.argv[1:]:
        stale = out_of_date()
        for path in stale:
            print(f"{path} is out of date; run: python3 scripts/sync_index.py")
        sys.exit(1 if stale else 0)

    skills = ready_skills()
    README.write_text(expected_readme(skills), encoding="utf-8")
    MARKETPLACE.write_text(expected_marketplace(skills), encoding="utf-8")
    print(f"Synced README index and marketplace.json ({len(skills)} skill(s)).")


if __name__ == "__main__":
    main()
